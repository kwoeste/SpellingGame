/**
 * Import NotebookLM media for any chapters present under NLM_MEDIA_DIR
 * (default /workspace/notebooklm/media/<chapterId>/{video.mp4,audio.m4a,flashcards.json}).
 *
 *   npx tsx --env-file=.env.local scripts/nlm-import.ts [chapterId ...]
 *
 * - video/audio go to the PRIVATE Vercel Blob store (needs BLOB_READ_WRITE_TOKEN; `vercel env pull .env.local`).
 * - flashcards.json is validated and copied to lib/content/flashcards/<chapterId>.json.
 * - lib/content/nlm-media.json and lib/content/flashcards/index.ts are rewritten.
 * Safe to re-run: files whose sha256 already matches the manifest are skipped.
 * Then commit the JSON changes, PR, merge, deploy.
 */
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { put } from "@vercel/blob";
import { getChapter } from "@/lib/content/catalog";
import { isFlashcardList } from "@/lib/content/nlm";

const ROOT = process.cwd();
const MEDIA_DIR = process.env.NLM_MEDIA_DIR ?? "/workspace/notebooklm/media";
const MANIFEST = path.join(ROOT, "lib/content/nlm-media.json");
const CARDS_DIR = path.join(ROOT, "lib/content/flashcards");
const FILES = { video: { file: "video.mp4", type: "video/mp4", ext: "mp4" }, audio: { file: "audio.m4a", type: "audio/mp4", ext: "m4a" } } as const;

type Entry = { pathname: string; contentType: string; size: number; sha256: string };
const manifest = JSON.parse(readFileSync(MANIFEST, "utf8")) as Record<string, Record<string, Entry>>;

function sha256(file: string): string {
  return createHash("sha256").update(readFileSync(file)).digest("hex");
}

function writeCardIndex() {
  const ids = readdirSync(CARDS_DIR).filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, "")).sort();
  const lines = [
    "// Generated by scripts/nlm-import.ts. Do not edit by hand.",
    'import type { Flashcard } from "@/lib/content/nlm";',
    ...ids.map((id, i) => `import c${i} from "@/lib/content/flashcards/${id}.json";`),
    "",
    "export const FLASHCARDS: Record<string, Flashcard[]> = {",
    ...ids.map((id, i) => `  ${JSON.stringify(id)}: c${i},`),
    "};",
    "",
  ];
  writeFileSync(path.join(CARDS_DIR, "index.ts"), lines.join("\n"));
}

async function main() {
  const only = process.argv.slice(2);
  const dirs = existsSync(MEDIA_DIR) ? readdirSync(MEDIA_DIR).filter((d) => statSync(path.join(MEDIA_DIR, d)).isDirectory()) : [];
  for (const id of dirs) {
    if (only.length && !only.includes(id)) continue;
    if (!getChapter(id)) {
      console.warn(`skip ${id}: not a chapter id`);
      continue;
    }
    const dir = path.join(MEDIA_DIR, id);
    for (const [kind, spec] of Object.entries(FILES)) {
      const file = path.join(dir, spec.file);
      if (!existsSync(file)) continue;
      const hash = sha256(file);
      if (manifest[id]?.[kind]?.sha256 === hash) {
        console.log(`ok   ${id} ${kind} (unchanged)`);
        continue;
      }
      const size = statSync(file).size;
      const pathname = `nlm/${id}/${kind}-${hash.slice(0, 12)}.${spec.ext}`;
      const blob = await put(pathname, readFileSync(file), { access: "private", contentType: spec.type, multipart: size > 8_000_000, allowOverwrite: true, addRandomSuffix: false });
      manifest[id] = { ...manifest[id], [kind]: { pathname: blob.pathname, contentType: spec.type, size, sha256: hash } };
      console.log(`up   ${id} ${kind} ${(size / 1e6).toFixed(1)} MB -> ${blob.pathname}`);
      writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2) + "\n");
    }
    const cardsFile = path.join(dir, "flashcards.json");
    if (existsSync(cardsFile)) {
      const raw = JSON.parse(readFileSync(cardsFile, "utf8")) as { front: string; back: string }[];
      const cards = Array.isArray(raw) ? raw.map((c) => ({ front: String(c.front ?? "").trim(), back: String(c.back ?? "").trim() })) : [];
      if (!isFlashcardList(cards)) throw new Error(`${cardsFile}: expected [{front, back}]`);
      writeFileSync(path.join(CARDS_DIR, `${id}.json`), JSON.stringify(cards, null, 2) + "\n");
      console.log(`ok   ${id} flashcards (${cards.length})`);
    }
  }
  const sorted = Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(MANIFEST, JSON.stringify(sorted, null, 2) + "\n");
  writeCardIndex();
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
